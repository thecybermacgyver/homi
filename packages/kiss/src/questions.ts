// Seed deck order: interleaved so a stretch of days always mixes moods.
export interface Question { readonly id: string; readonly kind: QuestionKind; readonly text: string }

function tag(kind: QuestionKind, list: readonly string[]): Question[] {
  return list.map((text, index) => ({ id: `${kind}-${index + 1}`, kind, text }));
}

